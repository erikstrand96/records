package models

import (
	"encoding/json"
	"fmt"
	"maps"
	"net/http"
)

// ContentTypeProblemJSON is the MIME media type for RFC 9457 problem details.
const ContentTypeProblemJSON = "application/problem+json"

// ProblemDetails represents an RFC 9457 Problem Details object.
// See https://www.rfc-editor.org/rfc/rfc9457.html
type ProblemDetails struct {
	// Type is a URI reference that identifies the problem type.
	// When dereferenced, it can provide human-readable documentation for the problem type.
	// When not present, its value is assumed to be "about:blank".
	Type string `json:"type,omitempty"`

	// Title is a short, human-readable summary of the problem type.
	// It SHOULD NOT change from occurrence to occurrence of the problem.
	Title string `json:"title,omitempty"`

	// Status is the HTTP status code generated by the origin server for this occurrence of the problem.
	Status int `json:"status,omitempty"`

	// Detail is a human-readable explanation specific to this occurrence of the problem.
	Detail string `json:"detail,omitempty"`

	// Instance is a URI reference that identifies the specific occurrence of the problem.
	Instance string `json:"instance,omitempty"`

	// Extensions contains additional problem type specific members (RFC 9457 section 3.2).
	// Extension members are serialized as top-level JSON properties alongside standard members.
	Extensions map[string]any `json:"-"`
}

// Problem is an alias for ProblemDetails for convenience.
type Problem = ProblemDetails

// NewProblemDetails creates a new ProblemDetails object with default title corresponding to the HTTP status.
func NewProblemDetails(status int, detail string) *ProblemDetails {
	title := http.StatusText(status)
	return &ProblemDetails{
		Type:   "about:blank",
		Title:  title,
		Status: status,
		Detail: detail,
	}
}

// NewProblemDetailsWithTitle creates a new ProblemDetails object with explicit status, title, and detail.
func NewProblemDetailsWithTitle(status int, title, detail string) *ProblemDetails {
	if title == "" {
		title = http.StatusText(status)
	}
	return &ProblemDetails{
		Type:   "about:blank",
		Title:  title,
		Status: status,
		Detail: detail,
	}
}

// WithType sets the problem type URI.
func (p *ProblemDetails) WithType(problemType string) *ProblemDetails {
	p.Type = problemType
	return p
}

// WithTitle sets the problem title.
func (p *ProblemDetails) WithTitle(title string) *ProblemDetails {
	p.Title = title
	return p
}

// WithStatus sets the HTTP status code.
func (p *ProblemDetails) WithStatus(status int) *ProblemDetails {
	p.Status = status
	return p
}

// WithDetail sets the problem detail message.
func (p *ProblemDetails) WithDetail(detail string) *ProblemDetails {
	p.Detail = detail
	return p
}

// WithInstance sets the problem instance URI.
func (p *ProblemDetails) WithInstance(instance string) *ProblemDetails {
	p.Instance = instance
	return p
}

// WithExtension sets an additional extension property.
func (p *ProblemDetails) WithExtension(key string, value any) *ProblemDetails {
	if p.Extensions == nil {
		p.Extensions = make(map[string]any)
	}
	p.Extensions[key] = value
	return p
}

// WithExtensions sets multiple extension properties.
func (p *ProblemDetails) WithExtensions(extensions map[string]any) *ProblemDetails {
	if p.Extensions == nil {
		p.Extensions = make(map[string]any, len(extensions))
	}
	maps.Copy(p.Extensions, extensions)
	return p
}

// Error implements the standard error interface.
func (p *ProblemDetails) Error() string {
	if p == nil {
		return "problem details error"
	}
	if p.Detail != "" && p.Title != "" {
		if p.Status != 0 {
			return fmt.Sprintf("%d %s: %s", p.Status, p.Title, p.Detail)
		}
		return fmt.Sprintf("%s: %s", p.Title, p.Detail)
	}
	if p.Detail != "" {
		if p.Status != 0 {
			return fmt.Sprintf("%d: %s", p.Status, p.Detail)
		}
		return p.Detail
	}
	if p.Title != "" {
		if p.Status != 0 {
			return fmt.Sprintf("%d %s", p.Status, p.Title)
		}
		return p.Title
	}
	if p.Status != 0 {
		return fmt.Sprintf("HTTP %d", p.Status)
	}
	return "problem details error"
}

// MarshalJSON custom marshaler to serialize extension members at the top level of the JSON object.
func (p *ProblemDetails) MarshalJSON() ([]byte, error) {
	if p == nil {
		return []byte("null"), nil
	}
	m := make(map[string]any, len(p.Extensions)+5)
	maps.Copy(m, p.Extensions)
	if p.Type != "" {
		m["type"] = p.Type
	}
	if p.Title != "" {
		m["title"] = p.Title
	}
	if p.Status != 0 {
		m["status"] = p.Status
	}
	if p.Detail != "" {
		m["detail"] = p.Detail
	}
	if p.Instance != "" {
		m["instance"] = p.Instance
	}
	return json.Marshal(m)
}

// UnmarshalJSON custom unmarshaler to extract standard members and any extension members.
func (p *ProblemDetails) UnmarshalJSON(data []byte) error {
	var raw map[string]any
	if err := json.Unmarshal(data, &raw); err != nil {
		return err
	}

	if v, ok := raw["type"].(string); ok {
		p.Type = v
		delete(raw, "type")
	}
	if v, ok := raw["title"].(string); ok {
		p.Title = v
		delete(raw, "title")
	}
	if v, ok := raw["status"]; ok {
		switch num := v.(type) {
		case float64:
			p.Status = int(num)
		case int:
			p.Status = num
		case json.Number:
			if n, err := num.Int64(); err == nil {
				p.Status = int(n)
			}
		}
		delete(raw, "status")
	}
	if v, ok := raw["detail"].(string); ok {
		p.Detail = v
		delete(raw, "detail")
	}
	if v, ok := raw["instance"].(string); ok {
		p.Instance = v
		delete(raw, "instance")
	}

	if len(raw) > 0 {
		p.Extensions = raw
	} else {
		p.Extensions = nil
	}
	return nil
}

// Write sets the Content-Type header to application/problem+json, sets the HTTP status code,
// and writes the JSON-encoded ProblemDetails to the response writer.
func (p *ProblemDetails) Write(w http.ResponseWriter) error {
	if p == nil {
		return nil
	}
	w.Header().Set("Content-Type", ContentTypeProblemJSON)
	status := p.Status
	if status < 100 || status > 599 {
		status = http.StatusInternalServerError
	}
	w.WriteHeader(status)
	return json.NewEncoder(w).Encode(p)
}

// WriteProblem is a helper function to write a ProblemDetails to an http.ResponseWriter.
func WriteProblem(w http.ResponseWriter, p *ProblemDetails) error {
	return p.Write(w)
}
